import { describe, expect, it } from "vitest";
import { compose, decompose, isJamo } from "./jamo";

describe("decompose", () => {
  it.each([
    ["계산", "ㄱㅕㅣㅅㅏㄴ"],
    ["날씨", "ㄴㅏㄹㅅㅅㅣ"],
    ["원고", "ㅇㅜㅓㄴㄱㅗ"],
    // 쌍자음 초성
    ["까따빠싸짜", "ㄱㄱㅏㄷㄷㅏㅂㅂㅏㅅㅅㅏㅈㅈㅏ"],
    // 모음 조합 11종
    ["애얘에예와왜외워웨위의", "ㅇㅏㅣㅇㅑㅣㅇㅓㅣㅇㅕㅣㅇㅗㅏㅇㅗㅏㅣㅇㅗㅣㅇㅜㅓㅇㅜㅓㅣㅇㅜㅣㅇㅡㅣ"],
    // 쌍받침 2종과 겹받침 11종
    ["깎있몫앉않닭삶밟곬핥읊싫값", "ㄱㄱㅏㄱㄱㅇㅣㅅㅅㅁㅗㄱㅅㅇㅏㄴㅈㅇㅏㄴㅎㄷㅏㄹㄱㅅㅏㄹㅁㅂㅏㄹㅂㄱㅗㄹㅅㅎㅏㄹㅌㅇㅡㄹㅍㅅㅣㄹㅎㄱㅏㅂㅅ"],
  ])("%s → %s", (word, jamo) => {
    expect(decompose(word)).toEqual([...jamo]);
  });

  it("한글 음절이 아닌 글자가 있으면 null", () => {
    expect(decompose("계산1")).toBeNull();
    expect(decompose("ㄱㅏ")).toBeNull();
  });

  it("분해 결과는 기본 자모 24종뿐이다", () => {
    expect(decompose("뷁쐤꿿")!.every(isJamo)).toBe(true);
  });
});

describe("compose", () => {
  it.each([
    ["ㄴㅏㄹㅅㅅㅣ", "날씨"], // 낤시가 아님
    ["ㄱㅏㄱㄱㅏㅇ", "가깡"], // 각강이 아님: 뒤 음절 초성 쌍자음 우선
    ["ㄷㅏㄹㄱㅇㅣ", "닭이"], // ㄱㅇ은 초성이 안 되어 한 자모 초성
    ["ㅇㅏㄴㅈㅇㅏ", "앉아"],
    ["ㄱㄱㅏㄴㄴㅏ", "깐나"],
    ["ㄱㅕㅣㅅㅏㄴ", "계산"],
    ["ㅇㅜㅓㄴㄱㅗ", "원고"],
  ])("%s → %s", (jamo, word) => {
    expect(compose([...jamo])).toBe(word);
  });

  it.each([
    ["ㄱㅏㄴㅁㄹㅏ", "ㄴㅁ은 종성이 될 수 없음"],
    ["ㄱㅏㅏㄴㅏㄴ", "ㅏㅏ는 중성이 될 수 없음"],
    ["ㅏㄱㅏㄴㅏㄴ", "초성 없이 시작"],
    ["ㄱㅏㄷㅏㄷㄷ", "ㄸ은 종성이 될 수 없음"],
    ["ㄱㄴㄷㄹㅁㅂ", "모음 없음"],
  ])("%s 는 조합 불가(%s)", (jamo) => {
    expect(compose([...jamo])).toBeNull();
  });
});
